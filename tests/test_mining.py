def test_uncommitted_lines_belong_to_the_local_user(tmp_path: Path) -> None:
    """Working-tree edits are the local user's voice, not nobody's."""
    root = tmp_path / "wip"
    root.mkdir()
    _git(root, "init", "-q", "-b", "main")
    _git(root, "config", "commit.gpgsign", "false")
    _git(root, "config", "user.email", ALICE)
