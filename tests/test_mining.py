def test_mine_prs_uses_argv_list_with_timeout(repo: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    calls: list[tuple[list[str], int]] = []
    real_run = mining._run

    def fake_run(argv: list[str], cwd: Path, timeout: int) -> tuple[int, str]:
        calls.append((argv, timeout))
        if argv[0] == "gh":
            return 0, "[]"
        return real_run(argv, cwd, timeout)

    monkeypatch.setattr(mining, "_run", fake_run)
    mining.mine_prs(repo, author="me@gretchenboria.com")
    gh_calls = [c for c in calls if c[0][0] == "gh"]
    assert gh_calls, "mine_prs should shell out to gh"
    argv, timeout = gh_calls[0]
    assert isinstance(argv, list) and argv[:3] == ["gh", "pr", "list"]
    assert isinstance(timeout, int) and 0 < timeout <= 60
    assert all(isinstance(a, str) for a in argv)


