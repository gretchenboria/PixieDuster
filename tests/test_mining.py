def test_mine_all_prs_false_makes_no_gh_call(two_author_repo: Path,
                                             monkeypatch: pytest.MonkeyPatch) -> None:
    calls: list[list[str]] = []
    real_run = mining._run

    def watching_run(argv: list[str], cwd: Path, timeout: int) -> tuple[int, str]:
        calls.append(argv)
        return real_run(argv, cwd, timeout)

    monkeypatch.setattr(mining, "_run", watching_run)

    def explode(*a: object, **k: object) -> list[Sample]:
        raise AssertionError("mine_prs must not run when prs=False")

    monkeypatch.setattr(mining, "mine_prs", explode)
    samples = mining.mine_all(two_author_repo, prs=False)
    assert samples
    assert not any(argv and argv[0] == "gh" for argv in calls)
    assert not any(s.kind == "pr" for s in samples)


def test_mine_all_prs_true_by_default(two_author_repo: Path,
                                      monkeypatch: pytest.MonkeyPatch) -> None:
    called: list[bool] = []

    def fake_prs(*a: object, **k: object) -> list[Sample]:
        called.append(True)
        return []

    monkeypatch.setattr(mining, "mine_prs", fake_prs)
    mining.mine_all(two_author_repo)
    assert called == [True]


def test_mine_all_prs_false_redistributes_the_pr_share(
    two_author_repo: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(mining, "mine_prs", lambda *a, **k: [])
    budget = 900
    without = mining.mine_all(two_author_repo, budget_chars=budget, prs=False)
    assert sum(len(s.text) for s in without) <= budget
    # the 15% PR share is donated, not wasted
    quotas = mining._quotas(
        {"commit": 10**6, "doc": 10**6, "comment": 10**6, "pr": 0}, 1000
    )
    assert quotas["pr"] == 0
    assert sum(quotas[k] for k in ("commit", "doc", "comment")) > 950


