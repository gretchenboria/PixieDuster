def test_safe_path_rejects_escapes_and_symlinks(repo: Path, tmp_path: Path) -> None:
    outside = tmp_path / "outside.md"
    outside.write_text("secret")
    link = repo / "link.md"
    if link.exists() or link.is_symlink():
        link.unlink()
    link.symlink_to(outside)
    try:
        assert mining._safe_path(repo, "link.md") is None
        assert mining._safe_path(repo, "../outside.md") is None
        assert mining._safe_path(repo, "/etc/hosts") is None
        assert mining._safe_path(repo, "") is None
        assert mining._safe_path(repo, "README.md") is not None
    finally:
        link.unlink()


